//! The IF97 coefficient tables, transcribed verbatim from R7-97(2012).
//!
//! Each region's dimensionless equation is a sum of terms `nᵢ · x^Iᵢ · y^Jᵢ`.
//! The exponents `Iᵢ`, `Jᵢ` are small integers (stored as `i32` so they feed
//! `f64::powi`), and `nᵢ` is a `f64` coefficient. Keeping every table in one
//! module makes them auditable against the printed standard in a single place,
//! and keeps the per-region math files readable.
//!
//! Source tables:
//! - Region 1 residual `γ`: R7-97(2012) Table 2 (34 terms).
//! - Region 2 ideal `γ°`: Table 10 (9 terms); residual `γʳ`: Table 11 (43).
//! - Region 5 ideal `γ°`: Table 37 (6 terms); residual `γʳ`: Table 38 (6).
//! - Region 3 `φ`: Table 30 (40 terms; term 1 is the `n₁·ln δ` term).

/// One `(I, J, n)` triple of a region's series.
pub(crate) struct Term {
    /// Exponent on the pressure-like variable (`i32` for `powi`).
    pub i: i32,
    /// Exponent on the temperature-like variable.
    pub j: i32,
    /// Coefficient `nᵢ`.
    pub n: f64,
}

/// Convenience constructor so the tables below read like the printed rows.
const fn t(i: i32, j: i32, n: f64) -> Term {
    Term { i, j, n }
}

